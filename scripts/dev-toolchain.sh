#!/usr/bin/env bash
#
# dev-toolchain.sh - prepare a cgo-capable Go toolchain for sandboxed agents.
#
# The burstel module uses github.com/duckdb/duckdb-go/v2, which is cgo and
# links a prebuilt static libduckdb. On build-host-1 `go` and `gcc` are not on
# the default PATH, but both are available through Nix. This script realizes
# them (network/binary-cache access is required on a cold store), writes a
# mode-600 environment file under the gitignored .scratch/, and prints it.
#
# Usage:
#   source <(scripts/dev-toolchain.sh)   # export PATH/CC/CXX for this shell
#   scripts/dev-toolchain.sh --write     # only write .scratch/toolchain.env
#
# No binary is ever committed: .scratch/ is in .gitignore.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SCRATCH="$REPO_ROOT/.scratch"
ENV_FILE="$SCRATCH/toolchain.env"
NIXPKGS="${NIXPKGS:-nixpkgs}"

mkdir -p "$SCRATCH"
chmod 700 "$SCRATCH"

need() { command -v "$1" >/dev/null 2>&1; }

GO_BIN=""
GCC_BIN=""

if need go; then
  GO_BIN="$(command -v go)"
fi
if need gcc; then
  GCC_BIN="$(command -v gcc)"
fi

if [ -z "$GO_BIN" ] || [ -z "$GCC_BIN" ]; then
  NIX_BIN="$(command -v nix 2>/dev/null || true)"
  if [ -z "$NIX_BIN" ] && [ -x /nix/var/nix/profiles/default/bin/nix ]; then
    NIX_BIN=/nix/var/nix/profiles/default/bin/nix
  fi
  if [ -z "$NIX_BIN" ]; then
    echo "dev-toolchain: go/gcc are missing and nix is unavailable" >&2
    echo "dev-toolchain: install go + a C compiler, or provide nix on PATH" >&2
    exit 1
  fi

  echo "dev-toolchain: realizing $NIXPKGS#{go,gcc} (may download from cache.nixos.org)" >&2
  # shellcheck disable=SC2046
  PATHS="$("$NIX_BIN" build --no-link --print-out-paths "$NIXPKGS#go" "$NIXPKGS#gcc")"

  for p in $PATHS; do
    if [ -z "$GO_BIN" ] && [ -x "$p/bin/go" ]; then GO_BIN="$p/bin/go"; fi
    if [ -z "$GCC_BIN" ] && [ -x "$p/bin/gcc" ]; then GCC_BIN="$p/bin/gcc"; fi
  done
fi

if [ -z "$GO_BIN" ] || [ -z "$GCC_BIN" ]; then
  echo "dev-toolchain: could not resolve both go and gcc" >&2
  exit 1
fi

GO_DIR="$(dirname "$GO_BIN")"
GCC_DIR="$(dirname "$GCC_BIN")"
GXX_BIN="$GCC_DIR/g++"

umask 077
cat >"$ENV_FILE" <<EOF
# Generated by scripts/dev-toolchain.sh. Source it: . .scratch/toolchain.env
export PATH="$GO_DIR:$GCC_DIR:\$PATH"
export CC="$GCC_BIN"
export CXX="$GXX_BIN"
export CGO_ENABLED=1
EOF
chmod 600 "$ENV_FILE"

if [ "${1:-}" = "--write" ]; then
  echo "dev-toolchain: wrote $ENV_FILE" >&2
  exit 0
fi

cat "$ENV_FILE"
